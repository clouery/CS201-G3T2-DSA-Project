package tdtsp.experiment;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/** Writes an experiment folder's README: question, config, how to reproduce, results and plots. */
final class Readme {

    static final String COMMON_NOTES = """
            - Instances: top-`n` cities by population from `data/processed/cities_all.csv`, network and \
            timetable from `NetworkGenerator` with the base `config.properties`, overriding only the \
            seed, headways and transfer buffer listed above. The train headway is `trainHeadwayFactor` \
            times the bus headway.
            - The generated timetable covers one service day (06:00-22:00). It is repeated for `days` \
            consecutive days so that multi-day tours remain feasible; day `d` is shifted by `d * 1440` minutes.
            - Runtimes are wall-clock on the machine that ran the experiment and vary between runs; \
            all other values are deterministic for a given config.
            """;

    private Readme() {
    }

    static void write(Path dir, String title, String question, ExperimentConfig config, String id,
                      List<String> outputs, String results, String notes) throws IOException {
        StringBuilder md = new StringBuilder();
        md.append("# ").append(title).append("\n\n");
        md.append(question).append("\n\n");
        md.append("> Generated by `tdtsp.experiment.ExperimentMain`; edit `config.properties`, not this file.\n\n");
        md.append("## Reproduce\n\n```\nmvn -q compile\n")
                .append("java -cp target/classes tdtsp.experiment.ExperimentMain ").append(id).append("\n```\n\n");
        md.append("## Config\n\n```properties\n").append(config.text()).append("\n```\n\n");
        md.append("## Outputs\n\n");
        for (String o : outputs) {
            md.append("- ").append(o).append('\n');
        }
        md.append("\n## Results (mean over seeds)\n\n").append(results).append('\n');
        md.append("## Notes\n\n").append(COMMON_NOTES).append(notes);
        if (!Instance.SUBSTITUTIONS.isEmpty()) {
            md.append("\n### Seed substitutions\n\n");
            for (String s : Instance.SUBSTITUTIONS) {
                md.append("- ").append(s).append('\n');
            }
        }
        md.append('\n');
        Files.writeString(dir.resolve("README.md"), md.toString(), StandardCharsets.UTF_8);
    }

    static String plot(String file, String alt) {
        return "![" + alt + "](plots/" + file + ")\n\n";
    }
}
