package tdtsp.experiment;

import java.io.IOException;
import java.io.Reader;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Properties;
import java.util.stream.Stream;

import tdtsp.network.Csv;
import tdtsp.network.NetworkGenerator;
import tdtsp.routing.TransitNetwork;

/**
 * One generated instance (plan §6 procedure, steps 1-2): the top-{@code n} cities by
 * population, a network and timetable from {@link NetworkGenerator} with the given
 * seed, headways and buffer, loaded as a multi-day {@link TransitNetwork}.
 */
record Instance(int cities, int seed, int busHeadway, int trainHeadway, int buffer, TransitNetwork network) {

    /** Root-level inputs shared by every experiment. */
    static final Path BASE_CONFIG = Path.of("config.properties");
    static final Path CITIES_ALL = Path.of("data/processed/cities_all.csv");

    /** Seeds replaced because the generator could not build a network, reported in the README. */
    static final List<String> SUBSTITUTIONS = new ArrayList<>();

    /**
     * Generates the instance for {@code seed}. If the generator cannot build a valid
     * network (e.g. it cannot cover every city within 12 lines of at most 8 stops), the
     * network is generated with {@code seed + 1000}, then {@code + 2000}, and so on.
     * The returned {@link #seed()} is the requested seed.
     */
    static Instance generate(int cities, int seed, int busHeadway, int trainHeadway, int buffer, int days)
            throws IOException {
        for (int networkSeed = seed; ; networkSeed += 1000) {
            try {
                Instance inst = generateExactly(cities, networkSeed, busHeadway, trainHeadway, buffer, days);
                if (networkSeed != seed) {
                    String note = String.format(
                            "cities=%d, headway=%d/%d, buffer=%d: seed %d failed in the generator, network seed %d used",
                            cities, busHeadway, trainHeadway, buffer, seed, networkSeed);
                    SUBSTITUTIONS.add(note);
                    System.out.println("    " + note);
                }
                return new Instance(cities, seed, busHeadway, trainHeadway, buffer, inst.network());
            } catch (IllegalStateException e) {
                if (networkSeed >= seed + 10_000) {
                    throw e;
                }
            }
        }
    }

    private static Instance generateExactly(int cities, int seed, int busHeadway, int trainHeadway, int buffer,
                                            int days) throws IOException {
        Path dir = Files.createTempDirectory("tdtsp-instance");
        try {
            List<String[]> all = Csv.read(CITIES_ALL);
            if (all.size() - 1 < cities) {
                throw new IllegalArgumentException("only " + (all.size() - 1) + " cities available");
            }
            Path citiesCsv = dir.resolve("cities.csv");
            Csv.write(citiesCsv, new ArrayList<>(all.subList(0, cities + 1)));

            Properties properties = new Properties();
            try (Reader reader = Files.newBufferedReader(BASE_CONFIG, StandardCharsets.UTF_8)) {
                properties.load(reader);
            }
            properties.setProperty("seed", Integer.toString(seed));
            properties.setProperty("headway.busMin", Integer.toString(busHeadway));
            properties.setProperty("headway.trainMin", Integer.toString(trainHeadway));
            properties.setProperty("transfer.bufferMin", Integer.toString(buffer));
            Path config = dir.resolve("config.properties");
            try (Writer writer = Files.newBufferedWriter(config, StandardCharsets.UTF_8)) {
                properties.store(writer, "generated by tdtsp.experiment.Instance");
            }

            Path gtfs = dir.resolve("gtfs");
            new NetworkGenerator(config).generate(citiesCsv, dir.resolve("processed"), gtfs);
            TransitNetwork network = TransitNetwork.load(gtfs, days);
            return new Instance(cities, seed, busHeadway, trainHeadway, buffer, network);
        } finally {
            deleteRecursively(dir);
        }
    }

    int city(String name) {
        int index = network.indexOf(name);
        if (index < 0) {
            throw new IllegalArgumentException("city not in instance: " + name);
        }
        return index;
    }

    /** Complete haversine distance matrix, for the classic baseline. */
    double[][] distanceKm() {
        int n = network.numStops();
        double[][] d = new double[n][n];
        for (int i = 0; i < n; i++) {
            for (int j = 0; j < n; j++) {
                d[i][j] = NetworkGenerator.haversineKm(network.lat(i), network.lon(i), network.lat(j), network.lon(j));
            }
        }
        return d;
    }

    private static void deleteRecursively(Path dir) throws IOException {
        try (Stream<Path> paths = Files.walk(dir)) {
            for (Path p : paths.sorted(Comparator.reverseOrder()).toList()) {
                Files.deleteIfExists(p);
            }
        }
    }
}
